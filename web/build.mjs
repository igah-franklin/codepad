// Bundles the editor and runner into self-contained HTML strings for the React Native app.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const PYODIDE_VERSION = JSON.parse(readFileSync('node_modules/pyodide/package.json', 'utf8')).version;
const PYODIDE_BASE = process.env.PYODIDE_BASE || `https://cdn.jsdelivr.net/pyodide/v${PYODIDE_VERSION}/full/`;
const TEST = !!process.env.PYODIDE_BASE;

const bundle = async (entry, extra = {}) => {
  const r = await build({ entryPoints: [entry], bundle: true, minify: true, format: 'iife', write: false, target: ['es2020'], ...extra });
  return r.outputFiles[0].text;
};

const editorJs = await bundle('editor.js');
const jsWorker = await bundle('worker-js.js');
const pyWorker = await bundle('worker-py.js');
const runnerJs = await bundle('runner.js', {
  define: {
    __JS_WORKER_SRC__: JSON.stringify(jsWorker),
    __PY_WORKER_SRC__: JSON.stringify(pyWorker),
    __PYODIDE_BASE__: JSON.stringify(PYODIDE_BASE),
  },
});

const safe = (s) => s.replace(/<\/script/gi, '<\\/script');

const editorHtml = `<!DOCTYPE html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<style>html,body{margin:0;padding:0;height:100%;background:#0D1117;-webkit-tap-highlight-color:transparent;-webkit-text-size-adjust:100%}#editor{height:100%}.cm-editor{height:100%}.cm-editor.cm-focused{outline:none}</style>
</head><body><div id="editor"></div><script>${safe(editorJs)}</script></body></html>`;

const runnerHtml = `<!DOCTYPE html><html><head><meta charset="utf-8"></head><body><script>${safe(runnerJs)}</script></body></html>`;

if (TEST) { writeFileSync('test-runner.html', runnerHtml); console.log('test build'); process.exit(0); }
mkdirSync('../src/web', { recursive: true });
const header = '// AUTO-GENERATED by web/build.mjs — do not edit by hand.\n/* eslint-disable */\n';
writeFileSync('../src/web/editorHtml.ts', header + `export const EDITOR_HTML = ${JSON.stringify(editorHtml)};\n`);
writeFileSync('../src/web/runnerHtml.ts', header + `export const RUNNER_HTML = ${JSON.stringify(runnerHtml)};\nexport const PYODIDE_VERSION = ${JSON.stringify(PYODIDE_VERSION)};\n`);
// Standalone copies for browser testing
writeFileSync('dist-editor.html', editorHtml);
writeFileSync('dist-runner.html', runnerHtml);
console.log('editor', (editorHtml.length / 1024).toFixed(0) + 'KB', 'runner', (runnerHtml.length / 1024).toFixed(0) + 'KB', 'pyodide', PYODIDE_VERSION);
